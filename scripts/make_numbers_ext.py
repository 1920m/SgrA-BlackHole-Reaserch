def load(rel: str) -> dict | None:
    p = ROOT / rel
    if not p.exists():
        print(f"  [missing] {rel}")
        return None
    return json.loads(p.read_text())


def sig(x: float, n: int = 3) -> str:
    """n significant figures, thin-space thousands separator, no exponent."""
    if x == 0:
        return "0"
    d = n - int(math.floor(math.log10(abs(x)))) - 1
    v = round(x, d)
    if d <= 0:
        s = f"{int(round(v)):,}".replace(",", "\\,")
    else:
        s = f"{v:.{d}f}"
    return s


def sci(x: float, n: int = 2) -> str:
    """a\\times10^{b} with n significant figures."""
    e = int(math.floor(math.log10(abs(x))))
    m = x / 10 ** e
    if round(m, n - 1) >= 10:
        m /= 10
        e += 1
    return f"{m:.{n - 1}f}\\times10^{{{e}}}"


