    rg = load("validation/extension/g19_riaf_gpu.json")
    if rg:
        macro("XRiafGpuFluxDev", f"{100 * abs(rg['flux_ratio'] - 1):.1f}")
        macro("XRiafGpuCorr", f"{rg['correlation']:.4f}")
