            macro(f"XFcSigEnc{nm}", f"{100 * d['sigma_fenc_fixed_eps']:.3f}")
            macro(f"XFcSigEncMarg{nm}", f"{100 * d['sigma_fenc_marg_eps']:.3f}")
            macro(f"XFcInfl{nm}", f"{d['sigma_eps_marg_ext'] / d['sigma_eps_fixed_ext']:.2f}")
