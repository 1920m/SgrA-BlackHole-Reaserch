        macro("XIfRminus", f"{tr['r_minus']:.3f}")
        macro("XIfRstop", f"{tr['r_stop']:.3f}")
        macro("XIfRergo", f"{tr['r_ergo']:.3f}")
        macro("XIfTauErgo", f"{tr['tau_ergo']:.2f}")
