    # ---- Gate 22: forecasts ---------------------------------------------------
    fc = load("validation/extension/forecasts.json")
    if fc:
        A = fc["assumptions"]
        macro("XFcGravAst", f"{A['gravity']['sig_ast_uas']:.0f}")
        macro("XFcGravRate", f"{A['gravity']['ast_per_yr']:.0f}")
        macro("XFcGravRv", f"{A['gravity']['sig_rv_kms']:.0f}")
        macro("XFcGravRvRate", f"{A['gravity']['rv_per_yr']:.0f}")
        macro("XFcExAst", f"{A['existing_quality']['sig_ast_mas']:.1f}")
        macro("XFcExRate", f"{A['existing_quality']['ast_per_yr']:.1f}")
        macro("XFcExRv", f"{A['existing_quality']['sig_rv_kms']:.0f}")
        macro("XFcExRvRate", f"{A['existing_quality']['rv_per_yr']:.1f}")
        macro("XFcPlummer", f"{A['plummer_scale_mas'] / 1000:.1f}")
        macro("XFcApo", f"{A['apocentre_mas'] / 1000:.3f}")
        macro("XFcEncl", f"{100 * A['enclosed_per_total']:.1f}")
        macro("XFcPeriod", f"{A['period_yr']:.2f}")
        macro("XFcGspan", f"{A['g17']['span_yr']:.1f}")
        macro("XFcGnAst", str(A["g17"]["n_ast"]))
        macro("XFcGnRv", str(A["g17"]["n_rv"]))
        V = fc["validation"]
        macro("XFcSigEpsFisher", sig(V["sigma_eps_fisher"], 3))
        macro("XFcSigEpsThesis", sig(V["sigma_eps_thesis"], 3))
        macro("XFcSigEpsDiff", f"{100 * abs(V['sigma_eps_fisher'] / V['sigma_eps_thesis'] - 1):.1f}")
        macro("XFcSigMDiff", f"{100 * abs(V['sigma_M_fisher'] / V['sigma_M_thesis'] - 1):.2f}")
        T10 = fc["ten_orbits"]
        macro("XFcTenFisher", sig(T10["sigma_eps_fisher"], 3))
        macro("XFcTenThesis", sig(T10["sigma_eps_thesis_sqrtN"], 2))
        macro("XFcTenGain", sig(T10["gain_fisher"], 3))
        macro("XFcTenGainThesis", f"{T10['gain_sqrtN']:.1f}")
        gv = {round(e["T_yr"]): e["sigma_eps"] for e in fc["eps_vs_years"]["gravity"]}
        ex = {round(e["T_yr"]): e["sigma_eps"] for e in fc["eps_vs_years"]["existing_quality"]}
        for T, nm in ((8, "Eight"), (16, "Sixteen"), (32, "ThirtyTwo"), (64, "SixtyFour")):
            macro(f"XFcEpsGrav{nm}", sig(gv[T], 2))
            macro(f"XFcEpsEx{nm}", sig(ex[T], 2))
        tmax = fc["eps_vs_years"]["gravity"][-1]["T_yr"]
        for e in fc["lense_thirring"]:
            nm = {65.0: "SixtyFive", 30.0: "Thirty", 10.0: "Ten"}[e["sig_ast_uas"]]
            suffix = "Marg" if e.get("ext_marginalised") else ""
            for k, lab in (("T_3sigma_yr", "Three"), ("T_5sigma_yr", "Five")):
                v = e[k]
