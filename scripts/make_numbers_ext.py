    # ---- Gate 21: EXOTIC SPACETIME (not Sgr A*) — the Dneg wormhole ----------
    wh = load("validation/extension/wormhole.json")
    if wh:
        macro("XWhA", f"{2 * wh['a']:.2f}")
        macro("XWhW", f"{wh['W_closed']:.2f}")
        macro("XWhWoverM", f"{wh['W_over_M']:.5f}")
        macro("XWhM", f"{wh['M']:.5f}")
        macro("XWhWdiff", sci(max(abs(wh["W_numeric"] / wh["W_closed"] - 1), 1e-16), 1))
        cams = {int(round(c["l_c"])): c for c in wh["cameras"]}
        for lc, nm in ((2, "Two"), (6, "Six"), (15, "Fifteen")):
            c = cams[lc]
            macro(f"XWhR{nm}", f"{c['r_c']:.3f}")
            macro(f"XWhEdge{nm}", f"{c['edge_deg']:.3f}")
            macro(f"XWhRing{nm}", f"{c['einstein_ring_deg']:.3f}")
        macro("XWhEdgeErr", sci(max(max(abs(c["edge_deg"] - c["edge_analytic_deg"])
                                        for c in wh["cameras"]), 1e-16), 1))
        macro("XWhMaxdB", sci(max(wh["max_dB2"], 1e-17), 1))
        macro("XWhMaxH", sci(max(wh["max_H"], 1e-17), 1))
        macro("XWhRingShift", sci(max(wh["ring_lfar_shift_deg"], 1e-16), 1))
    whg = load("validation/extension/wormhole_gpu.json")
    if whg:
        macro("XWhGpuMaxPx", f"{whg['max_dev_px']:.2f}")
