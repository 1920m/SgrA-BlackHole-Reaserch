        macro("XIfTauInside", f"{tr['tau_inside']:.3f}")
        macro("XIfTauHorMin", f"{tr['tau_horizon'] * tg / 60:.1f}")
        macro("XIfTauErgoHorSec", f"{(tr['tau_horizon'] - tr['tau_ergo']) * tg:.1f}")
        macro("XIfTauInsideSec", f"{tr['tau_inside'] * tg:.1f}")
        macro("XIfTg", f"{tg:.1f}")
        macro("XIfRgKm", sig(tr["rg_km"], 3))
        macro("XIfRplusKm", sig(tr["r_plus"] * tr["rg_km"] / 1e6, 3))
        macro("XIfMaxdE", sci(max(tr["max_dE"], 1e-17), 1))
        macro("XIfMaxdL", sci(max(tr["max_dL"], 1e-17), 1))
        macro("XIfMaxdQ", sci(max(tr["max_dQ"], 1e-17), 1))
