"""Generate paper/numbers.tex — LaTeX macros for every number cited in the
paper, pulled directly from the simulation output JSONs (every
number must be reproducible via `make reproduce`; nothing hand-typed).

Run: py -3.11 scripts/make_numbers.py
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "paper" / "numbers.tex"


def load(rel: str) -> dict | None:
    p = ROOT / rel
    if not p.exists():
        print(f"  [missing] {rel}")
        return None
    return json.loads(p.read_text())


def main() -> None:
    lines: list[str] = [
        "% AUTO-GENERATED by scripts/make_numbers.py — do not edit by hand.",
        "% Regenerate with `make reproduce` / `py -3.11 scripts/make_numbers.py`.",
    ]

    def macro(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\{name}}}{{{value}}}")

    # ---- S2 orbit fit (Phase 4) --------------------------------------------
    fit = load("validation/phase4/s2_fit.json")
    if fit:
        macro("FitMass", f"{fit['M_msun'] / 1e6:.3f}")
        macro("FitMassErr", f"{fit['sigma_M_msun'] / 1e6:.3f}")
        macro("FitDist", f"{fit['R0_pc']:.0f}")
        macro("FitDistErr", f"{fit['sigma_R0_pc']:.0f}")
        macro("FitSma", f"{fit['a_mas']:.2f}")
        macro("FitSmaErr", f"{fit['sigma_a_mas']:.2f}")
        macro("FitEcc", f"{fit['e']:.5f}")
        macro("FitEccErr", f"{fit['sigma_e']:.5f}")
        macro("FitIncl", f"{fit['incl_deg']:.2f}")
        macro("FitInclErr", f"{fit['sigma_incl_deg']:.2f}")
        macro("FitOmegaBig", f"{fit['Omega_deg']:.2f}")
        macro("FitOmegaBigErr", f"{fit['sigma_Omega_deg']:.2f}")
        macro("FitOmegaSm", f"{fit['omega_deg']:.2f}")
        macro("FitOmegaSmErr", f"{fit['sigma_omega_deg']:.2f}")
        macro("FitTPeri", f"{fit['t_peri_yr']:.4f}")
        macro("FitTPeriErr", f"{fit['sigma_t_peri_yr']:.4f}")
        macro("FitPeriod", f"{fit['period_yr']:.4f}")
        macro("FitPeriodErr", f"{fit['sigma_period_yr']:.4f}")
        macro("FitChiTwo", f"{fit['chi2']:.1f}")
        macro("FitDof", f"{fit['dof']}")
        macro("FitChiRed", f"{fit['chi2_red']:.3f}")
        macro("FitNAst", f"{fit['n_astrometry']}")
        macro("FitNRv", f"{fit['n_rv']}")
        macro("GrExcessPeak", f"{fit['gr_excess_peak_kms']:.0f}")
        macro("GrExcessEpoch", f"{fit['gr_excess_peak_epoch']:.3f}")
        macro("PrecSchw", f"{fit['precession_schw_arcmin']:.2f}")
        macro("PrecLT", f"{fit['precession_lt_arcmin_a094']:.3f}")
        dm = abs(fit["M_msun"] - 4.297e6) / (fit["sigma_M_msun"] ** 2 + 0.012e6 ** 2) ** 0.5
        macro("FitMassNSigma", f"{dm:.2f}")
        dr = abs(fit["R0_pc"] - 8277.0) / (fit["sigma_R0_pc"] ** 2 + 9.0 ** 2) ** 0.5
        macro("FitDistNSigma", f"{dr:.2f}")

    # ---- No-hair (Phase 5) --------------------------------------------------
    nh = load("validation/phase5/s2_fit.json")
    if nh and "nohair" in nh:
        n = nh["nohair"]
        macro("EpsQBest", f"{n['eps_q_profile_min'] / 1e5:.2f}")
        macro("EpsQSigma", f"{n['eps_q_sigma'] / 1e5:.2f}")
        macro("EpsQCiNinetyFive", f"{n['eps_q_ci95_halfwidth'] / 1e5:.2f}")
        macro("EpsQForecastTenOrbits",
              f"{n['forecast_sigma_10_more_orbits'] / 1e5:.2f}")

    # ---- shadow metrology (Phases 1–2) --------------------------------------
    schw = load("validation/reference_images/schwarzschild_cpu.json")
    if schw:
        macro("SchwDiamM", f"{schw['shadow_diameter_M']:.4f}")
        dev = abs(schw["shadow_mean_alpha_rad"] /
                  (schw["shadow_max_alpha_rad"] or 1) - 1.0)
        macro("SchwSpreadPct",
              f"{100 * (schw['shadow_max_alpha_rad'] - schw['shadow_min_alpha_rad']) / schw['shadow_mean_alpha_rad']:.3f}")
    kerr = load("validation/reference_images/kerr_cpu_a94.json")
    if kerr:
        macro("KerrDiamM", f"{kerr['shadow_diameter_M']:.4f}")
        macro("KerrDiamUas", f"{kerr['shadow_diameter_uas_at_sgrA']:.2f}")

    # ---- disk / sub-rings (Phase 3) -----------------------------------------
    sub = load("validation/phase3/subring_report.json")
    if sub:
        macro("BeamRatio", f"{sub['beaming_flux_ratio']:.2f}")
        macro("GMin", f"{sub['g_min']:.3f}")
        macro("GMax", f"{sub['g_max']:.3f}")
        macro("FluxRatioZeroOne", f"{sub['flux_ratio_n0_n1']:.1f}")
        macro("FluxRatioOneTwo", f"{sub['flux_ratio_n1_n2']:.0f}")

    # ---- calibration (Phase 10) ---------------------------------------------
    cal = load("validation/phase10/calibration.json")
    if cal:
        macro("CalDiamUas", f"{cal['mean_uas']:.2f}")
        macro("CalDiamM", f"{cal['mean_M']:.3f}")
        macro("CalAxisRatio", f"{cal['axis_ratio']:.4f}")
        macro("UasPerM", f"{cal['uas_per_M']:.4f}")

    # ---- GPU comparison (Phase 7) -------------------------------------------
    cmp = load("validation/phase7/gpu_diag.png.compare.json")
    if cmp:
        macro("GpuMeanDiff", f"{cmp['mean_abs_diff']:.5f}")
        macro("GpuMaxDiff", f"{cmp['max_abs_diff']:.3f}")
        macro("GpuOutliers", f"{cmp['outlier_pixels']}")

    # ---- benchmarks (Phase 11) ----------------------------------------------
    bench = load("validation/phase11/bench.json")
    if bench:
        for k, v in bench.items():
            if isinstance(v, (int, float)):
                macro("Bench" + "".join(w.capitalize() for w in k.split("_")),
                      f"{v:g}")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines) - 2} macros)")


if __name__ == "__main__":
    main()
