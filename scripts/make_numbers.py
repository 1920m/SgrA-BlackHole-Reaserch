"""Generate paper/numbers.tex — LaTeX macros for every number cited in the
paper, pulled directly from the simulation output JSONs (every
number must be reproducible via `make reproduce`; nothing hand-typed).

Run: py -3.11 scripts/make_numbers.py
"""
from __future__ import annotations

import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "paper" / "numbers.tex"


def load(rel: str) -> dict | None:
    p = ROOT / rel
    if not p.exists():
        print(f"  [missing] {rel}")
        return None
    return json.loads(p.read_text())


def load_csv(rel: str) -> list[dict] | None:
    p = ROOT / rel
    if not p.exists():
        print(f"  [missing] {rel}")
        return None
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def main() -> None:
    lines: list[str] = [
        "% AUTO-GENERATED by scripts/make_numbers.py — do not edit by hand.",
        "% Regenerate with `make reproduce` / `py -3.11 scripts/make_numbers.py`.",
    ]

    def macro(name: str, value: str) -> None:
        lines.append(rf"\newcommand{{\{name}}}{{{value}}}")

    # ---- S2 orbit fit (Phase 4) --------------------------------------------
    fit = load("validation/phase4/s2_fit.json")
    if fit:
        macro("FitMass", f"{fit['M_msun'] / 1e6:.3f}")
        macro("FitMassErr", f"{fit['sigma_M_msun'] / 1e6:.3f}")
        macro("FitDist", f"{fit['R0_pc']:.0f}")
        macro("FitDistErr", f"{fit['sigma_R0_pc']:.0f}")
        macro("FitSma", f"{fit['a_mas']:.2f}")
        macro("FitSmaErr", f"{fit['sigma_a_mas']:.2f}")
        macro("FitEcc", f"{fit['e']:.5f}")
        macro("FitEccErr", f"{fit['sigma_e']:.5f}")
        macro("FitIncl", f"{fit['incl_deg']:.2f}")
        macro("FitInclErr", f"{fit['sigma_incl_deg']:.2f}")
        macro("FitOmegaBig", f"{fit['Omega_deg']:.2f}")
        macro("FitOmegaBigErr", f"{fit['sigma_Omega_deg']:.2f}")
        macro("FitOmegaSm", f"{fit['omega_deg']:.2f}")
        macro("FitOmegaSmErr", f"{fit['sigma_omega_deg']:.2f}")
        macro("FitTPeri", f"{fit['t_peri_yr']:.4f}")
        macro("FitTPeriErr", f"{fit['sigma_t_peri_yr']:.4f}")
        macro("FitPeriod", f"{fit['period_yr']:.4f}")
        macro("FitPeriodErr", f"{fit['sigma_period_yr']:.4f}")
        macro("FitChiTwo", f"{fit['chi2']:.1f}")
        macro("FitDof", f"{fit['dof']}")
        macro("FitChiRed", f"{fit['chi2_red']:.3f}")
        macro("FitNAst", f"{fit['n_astrometry']}")
        macro("FitNRv", f"{fit['n_rv']}")
        macro("GrExcessPeak", f"{fit['gr_excess_peak_kms']:.0f}")
        macro("GrExcessEpoch", f"{fit['gr_excess_peak_epoch']:.3f}")
        macro("PrecSchw", f"{fit['precession_schw_arcmin']:.2f}")
        macro("PrecLT", f"{fit['precession_lt_arcmin_a094']:.3f}")
        dm = abs(fit["M_msun"] - 4.297e6) / (fit["sigma_M_msun"] ** 2 + 0.012e6 ** 2) ** 0.5
        macro("FitMassNSigma", f"{dm:.2f}")
        dr = abs(fit["R0_pc"] - 8277.0) / (fit["sigma_R0_pc"] ** 2 + 9.0 ** 2) ** 0.5
        macro("FitDistNSigma", f"{dr:.2f}")

    # ---- No-hair (Phase 5) --------------------------------------------------
    nh = load("validation/phase5/s2_fit.json")
    if nh and "nohair" in nh:
        n = nh["nohair"]
        macro("EpsQBest", f"{n['eps_q_profile_min'] / 1e5:.2f}")
        macro("EpsQSigma", f"{n['eps_q_sigma'] / 1e5:.2f}")
        macro("EpsQCiNinetyFive", f"{n['eps_q_ci95_halfwidth'] / 1e5:.2f}")
        macro("EpsQForecastTenOrbits",
              f"{n['forecast_sigma_10_more_orbits'] / 1e5:.2f}")

    # ---- shadow metrology (Phases 1–2) --------------------------------------
    schw = load("validation/reference_images/schwarzschild_cpu.json")
    if schw:
        macro("SchwDiamM", f"{schw['shadow_diameter_M']:.4f}")
        dev = abs(schw["shadow_mean_alpha_rad"] /
                  (schw["shadow_max_alpha_rad"] or 1) - 1.0)
        macro("SchwSpreadPct",
              f"{100 * (schw['shadow_max_alpha_rad'] - schw['shadow_min_alpha_rad']) / schw['shadow_mean_alpha_rad']:.3f}")
    kerr = load("validation/reference_images/kerr_cpu_a94.json")
    if kerr:
        macro("KerrDiamM", f"{kerr['shadow_diameter_M']:.4f}")
        macro("KerrDiamUas", f"{kerr['shadow_diameter_uas_at_sgrA']:.2f}")

    # ---- disk / sub-rings (Phase 3) -----------------------------------------
    sub = load("validation/phase3/subring_report.json")
    if sub:
        macro("BeamRatio", f"{sub['beaming_flux_ratio']:.2f}")
        macro("GMin", f"{sub['g_min']:.3f}")
        macro("GMax", f"{sub['g_max']:.3f}")
        macro("FluxRatioZeroOne", f"{sub['flux_ratio_n0_n1']:.1f}")
        macro("FluxRatioOneTwo", f"{sub['flux_ratio_n1_n2']:.0f}")

    # ---- calibration (Phase 10) ---------------------------------------------
    cal = load("validation/phase10/calibration.json")
    if cal:
        macro("CalDiamUas", f"{cal['mean_uas']:.2f}")
        macro("CalDiamM", f"{cal['mean_M']:.3f}")
        macro("CalAxisRatio", f"{cal['axis_ratio']:.4f}")
        macro("UasPerM", f"{cal['uas_per_M']:.4f}")

    # ---- GPU comparison (Phase 7) -------------------------------------------
    cmp = load("validation/phase7/gpu_diag.png.compare.json")
    if cmp:
        macro("GpuMeanDiff", f"{cmp['mean_abs_diff']:.5f}")
        macro("GpuMaxDiff", f"{cmp['max_abs_diff']:.3f}")
        macro("GpuOutliers", f"{cmp['outlier_pixels']}")

    # ---- benchmarks (Phase 11) ----------------------------------------------
    bench = load("validation/phase11/bench.json")
    if bench:
        for k, v in bench.items():
            if isinstance(v, (int, float)):
                # Thousands separators for large counts (use in text mode);
                # %g would flip to scientific notation past 1e6.
                val = f"{v:,.0f}" if abs(v) >= 1e4 else f"{v:g}"
                macro("Bench" + "".join(w.capitalize() for w in k.split("_")),
                      val)

    # ---- thesis data tools (paper/THESIS_PLAN.md §2.3) ----------------------
    eff = load_csv("validation/thesis/efficiency_vs_spin.csv")
    if eff:
        def eta_at(a: float) -> float:
            row = min(eff, key=lambda r: abs(float(r["a_star"]) - a))
            return 100.0 * float(row["eta_pro"])
        macro("EtaSchw", f"{eta_at(0.0):.2f}")
        macro("EtaSgrA", f"{eta_at(0.94):.2f}")
        macro("EtaNearExtremal", f"{eta_at(0.998):.2f}")
    lyap = load_csv("validation/thesis/lyapunov_vs_spin.csv")
    if lyap:
        row = min(lyap, key=lambda r: abs(float(r["a_star"]) - 0.94))
        macro("GammaPolarSgrA", f"{float(row['gamma_polar']):.3f}")
        macro("GammaProSgrA", f"{float(row['gamma_pro']):.3f}")
        macro("GammaRetroSgrA", f"{float(row['gamma_retro']):.3f}")
    proj = load_csv("validation/thesis/projection_boundary.csv")
    if proj:
        on = [abs(float(r["rel_dev"])) for r in proj if r["projection"] == "1"]
        off = [abs(float(r["rel_dev"])) for r in proj if r["projection"] == "0"]
        macro("ProjOnWorstDev", f"{max(on):.1e}".replace("e-", r"\times10^{-") + "}")
        macro("ProjOffWorstPct", f"{100 * max(off):.0f}")
        macro("ProjOffBestDev", f"{min(off):.1e}".replace("e-", r"\times10^{-") + "}")
    sub_sw = load_csv("validation/thesis/subring_sweep.csv")
    if sub_sw:
        r01 = [float(r["ratio_n0_n1"]) for r in sub_sw]
        macro("SubringRatioZeroOneLo", f"{min(r01):.1f}")
        macro("SubringRatioZeroOneHi", f"{max(r01):.1f}")

    # ---- MCMC posterior (thesis Ch 9; scripts/run_mcmc.py) ------------------
    mc = load("validation/thesis/mcmc_s2.json")
    if mc:
        macro("McmcMassMed", f"{mc['M_msun'][1] / 1e6:.3f}")
        macro("McmcMassLo", f"{(mc['M_msun'][1] - mc['M_msun'][0]) / 1e6:.3f}")
        macro("McmcMassHi", f"{(mc['M_msun'][2] - mc['M_msun'][1]) / 1e6:.3f}")
        macro("McmcDistMed", f"{mc['R0_pc'][1]:.0f}")
        macro("McmcDistLo", f"{mc['R0_pc'][1] - mc['R0_pc'][0]:.0f}")
        macro("McmcDistHi", f"{mc['R0_pc'][2] - mc['R0_pc'][1]:.0f}")
        macro("McmcNSteps", f"{mc['n_steps']}")
        macro("McmcNWalkers", f"{mc['n_walkers']}")
        macro("McmcTauMax", f"{mc['autocorr_max']:.0f}")
        macro("McmcNSamples", f"{mc['n_samples']:,}".replace(",", "\\,"))
        macro("McmcChainTau", f"{mc['n_steps'] / mc['autocorr_max']:.0f}")
        macro("McmcAcceptance", f"{mc['acceptance']:.2f}")
    mcn = load("validation/thesis/mcmc_nohair.json")
    if mcn and "eps_q" in mcn:
        macro("McmcEpsQMed", f"{mcn['eps_q'][1] / 1e5:.2f}")
        macro("McmcEpsQLo", f"{(mcn['eps_q'][1] - mcn['eps_q'][0]) / 1e5:.2f}")
        macro("McmcEpsQHi", f"{(mcn['eps_q'][2] - mcn['eps_q'][1]) / 1e5:.2f}")

    # ---- multi-star cluster fit (thesis Ch 9.5) ------------------------------
    cl = load("validation/phase13/cluster_fit.json")
    if cl:
        macro("ClusterNStars", f"{len(cl['per_star'])}")
        macro("ClusterMass", f"{cl['M_msun'] / 1e6:.3f}")
        macro("ClusterMassErr", f"{cl['sigma_M_msun'] / 1e6:.3f}")
        macro("ClusterDist", f"{cl['R0_pc']:.0f}")
        macro("ClusterDistErr", f"{cl['sigma_R0_pc']:.0f}")
        macro("ClusterChiRed", f"{cl['chi2_red']:.3f}")
        sub = cl.get("subsets", [])
        if sub:
            macro("ClusterMassErrSTwoOnly",
                  f"{sub[0]['sigma_M_msun'] / 1e6:.3f}")
            macro("ClusterDistErrSTwoOnly", f"{sub[0]['sigma_R0_pc']:.0f}")
            impM = 100 * (1 - cl["sigma_M_msun"] / sub[0]["sigma_M_msun"])
            impR = 100 * (1 - cl["sigma_R0_pc"] / sub[0]["sigma_R0_pc"])
            macro("ClusterMassImprovePct", f"{impM:.0f}")
            macro("ClusterDistImprovePct", f"{impR:.0f}")
        nsig = abs(cl["M_msun"] - 4.297e6) / (
            cl["sigma_M_msun"] ** 2 + 0.012e6 ** 2) ** 0.5
        macro("ClusterMassNSigma", f"{nsig:.1f}")

    # ---- image-handedness correction (thesis appendix; handedness_tool) -----
    hd = load("validation/thesis/handedness.json")
    if hd:
        def sci(v: float) -> str:  # 2.7e-11 -> 2.7\times10^{-11} (math mode)
            if v == 0.0:
                return "0"
            m, e = f"{v:.1e}".split("e")
            return rf"{m}\times10^{{{int(e)}}}"

        b0, b9 = hd["beaming"]["a0"], hd["beaming"]["a094"]
        # corrected camera: left (approaching) over right; legacy: right/left
        macro("HandBeamAZero", f"{b0['physical']['left_over_right']:.1f}")
        macro("HandBeamAHigh", f"{b9['physical']['left_over_right']:.1f}")
        macro("HandBeamLegacyAZero", f"{1 / b0['legacy']['left_over_right']:.1f}")
        macro("HandBeamLegacyAHigh", f"{1 / b9['legacy']['left_over_right']:.1f}")
        s0 = hd["side_redshift"]["a0"]
        macro("HandGLeftAZero", f"{s0['physical']['g_left']:.3f}")
        macro("HandGRightAZero", f"{s0['physical']['g_right']:.3f}")
        macro("HandRHitAZero", f"{s0['physical']['r_left']:.1f}")
        mi = hd["mirror_identity"]
        macro("HandMirrorPixels", f"{mi['pixels']}")
        macro("HandMirrorMaxDiff",
              sci(max(mi["max_rel_dr"], mi["max_rel_dg"], mi["max_abs_phi_sum"])))
        se = hd["shadow_edges"]
        macro("HandXiLeft", f"{se['xi_left']:+.4f}")
        macro("HandXiRight", f"{se['xi_right']:+.4f}")
        macro("HandXiBardeenPro", f"{se['bardeen_xi_prograde']:+.4f}")
        macro("HandXiBardeenRetro", f"{se['bardeen_xi_retrograde']:+.4f}")
        macro("HandXiAgree", sci(max(
            abs(se["xi_left"] - se["bardeen_xi_prograde"]),
            abs(se["xi_right"] - se["bardeen_xi_retrograde"]))))
        ks = hd["kerr_schild_crosscheck"]
        macro("HandKSPixels", f"{ks['pixels']}")
        macro("HandKSOffAxisDr", sci(ks["max_rel_dr_off_axis"]))
        macro("HandKSOffAxisDg", sci(ks["max_rel_dg_off_axis"]))
        macro("HandKSAxisDr", sci(ks["max_rel_dr"]))
        macro("HandKSConsL", sci(ks["max_rel_dLz"]))
        macro("HandKSConsQ", sci(ks["max_rel_dQ"]))
        macro("HandKSConsH", sci(ks["max_rel_H"]))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(lines) - 2} macros)")


if __name__ == "__main__":
    main()
